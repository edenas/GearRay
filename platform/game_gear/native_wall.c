void wall_plan_prepare(const RaycasterRay *ray,NativeWallPlan *plan,unsigned char column)
{
    if(ray->wall_height>16) {
        memcpy(plan->rows,wall_source_rows[ray->wall_height-17],32);
        memcpy(plan->colors,wall_color_columns[ray->texture_id-1][ray->hit_side][ray->hit_offset>>5],8);
        plan->mode=0;
    } else {
        plan->mode=ray->wall_height<=8?3+(column&1):1+ray->hit_side;
        plan->top=(64-ray->wall_height)/2;
        plan->bottom=plan->top+ray->wall_height;
    }
}
void wall_plan_rows(unsigned char *dst,NativeWallPlan *left,NativeWallPlan *right,
                    unsigned char y,unsigned char count)
{
    const unsigned char *pair,*lp,*rp,*lflat=0,*rflat=0;
    unsigned char lr,rr,background=y<32?3:10,lc,rc;
    left->colors[15]=right->colors[15]=background;
    if(!left->mode && !right->mode) {
        while(count--) {
            lr=left->rows[y>>1];rr=right->rows[y>>1];
            if(y&1) {lr&=15;rr&=15;} else {lr>>=4;rr>>=4;}
            pair=native_wall_pairs[(left->colors[lr]<<4)|right->colors[rr]];
            dst[0]=pair[0];dst[1]=pair[1];dst[2]=pair[2];dst[3]=pair[3];
            dst+=4;++y;
        }
        return;
    }
    if(left->mode) lflat=left->mode>=3?&left_lod2_rows[left->mode-3][0][0]:
        left->mode==1?&left_lod1_x_rows[0][0]:&left_lod1_y_rows[0][0];
    if(right->mode) rflat=right->mode>=3?&right_lod2_rows[right->mode-3][0][0]:
        right->mode==1?&right_lod1_x_rows[0][0]:&right_lod1_y_rows[0][0];
    while(count--) {
        lc=rc=background;
        if(!left->mode) {lr=left->rows[y>>1];if(y&1)lr&=15;else lr>>=4;lc=left->colors[lr];}
        if(!right->mode) {rr=right->rows[y>>1];if(y&1)rr&=15;else rr>>=4;rc=right->colors[rr];}
        pair=native_wall_pairs[(lc<<4)|rc];
        lp=left->mode && y>=left->top && y<left->bottom?lflat+(y&7)*4:pair;
        rp=right->mode && y>=right->top && y<right->bottom?rflat+(y&7)*4:pair;
        dst[0]=(lp[0]&240)|(rp[0]&15);dst[1]=(lp[1]&240)|(rp[1]&15);
        dst[2]=(lp[2]&240)|(rp[2]&15);dst[3]=(lp[3]&240)|(rp[3]&15);
        dst+=4;++y;
    }
}

