param(
    [Parameter(Mandatory=$true)][string]$InputPath,
    [Parameter(Mandatory=$true)][string]$OutputHeader
)
$ErrorActionPreference='Stop'
# Build-time authoring tokens, not C expressions or runtime ASCII tile IDs.
$ids=@{X=8; E=0; S=1; B=2; D=5; R=6; W=7; G=10; '1'=9; '2'=11}
$text=[IO.File]::ReadAllText((Resolve-Path -LiteralPath $InputPath))
$rows=@($text.TrimEnd("`r","`n") -split '\r?\n')
if ($rows.Count -ne 13) { throw 'Workshop requires exactly 13 rows' }
$output=[Collections.Generic.List[string]]::new()
$output.Add('/* Generated by generate_workshop_map.ps1; edit game/workshop_map.layout. */')
$output.Add('static const unsigned char workshop_map[WORKSHOP_MAP_HEIGHT][WORKSHOP_MAP_WIDTH] = {')
foreach($row in $rows) {
    $tokens=@($row.Trim() -split '\s+')
    if ($tokens.Count -ne 13) { throw 'Workshop requires exactly 13 tokens per row' }
    $encoded=@(foreach($token in $tokens) {
        if (!$ids.ContainsKey($token) -or $token -cnotmatch '^(X|E|S|B|D|R|W|G|1|2)$') {
            throw "Unknown workshop token: $token"
        }
        $ids[$token]
    })
    $output.Add('    { '+($encoded -join ', ')+' },')
}
$output.Add('};')
$target=[IO.Path]::GetFullPath($OutputHeader)
[IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($target)) | Out-Null
[IO.File]::WriteAllText($target,($output -join "`n")+"`n",[Text.UTF8Encoding]::new($false))
