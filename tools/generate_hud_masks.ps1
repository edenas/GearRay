param(
    [Parameter(Mandatory=$true)][string]$GeneratedDirectory,
    [Parameter(Mandatory=$true)][string]$OutputHeader
)
$ErrorActionPreference = 'Stop'
# Consume the authoritative sprite generator output, including its per-art alpha.
# Four source rows per tile, each used twice: keep + four native plane bytes.
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('/* Generated by generate_hud_masks.ps1; do not edit. */')
$lines.Add('#ifndef GEAR_RAY_GENERATED_HUD_MASKS_H')
$lines.Add('#define GEAR_RAY_GENERATED_HUD_MASKS_H')
$lines.Add('#if HUD_WEAPON_WIDTH != 24 || HUD_WEAPON_HEIGHT != 24 || HUD_WEAPON_LEFT != 80 || HUD_WEAPON_TOP != 40 || HUD_SHOTGUN_WIDTH != 40 || HUD_SHOTGUN_HEIGHT != 32 || HUD_SHOTGUN_LEFT != 64 || HUD_SHOTGUN_TOP != 32 || HUD_WEAPON_RIGHT != 104 || HUD_WEAPON_BOTTOM != 64')
$lines.Add('#error Regenerate HUD mask layout for the new tile-aligned 2x geometry')
$lines.Add('#endif')
$total = 0
foreach ($art in @(
    @('weapon_texture','hud_weapon_pixels',24,24,8),
    @('weapon_shoot_texture','hud_weapon_shoot_pixels',24,24,8),
    @('shotgun_held','shotgun_held_pixels',40,32,10),
    @('shotgun_fire','shotgun_fire_pixels',40,32,10)
)) {
    $name=$art[0]; $symbol=$art[1]; $width=$art[2]; $height=$art[3]; $stride=$art[4]
    $source=Get-Content -LiteralPath (Join-Path $GeneratedDirectory "$name.c") -Raw
    $header=Get-Content -LiteralPath (Join-Path $GeneratedDirectory "$name.h") -Raw
    $body=[regex]::Match($source,'(?s)=\s*\{(.*?)\}').Groups[1].Value
    $pixels=@([regex]::Matches($body,'0x([0-9a-fA-F]+)') | ForEach-Object { [Convert]::ToInt32($_.Groups[1].Value,16) })
    $alphaMatch=[regex]::Match($header,"#define ${symbol}_TRANSPARENT_INDEX (\d+)")
    if (!$alphaMatch.Success -or $pixels.Count -ne $stride*$height/2) { throw "Invalid generated art: $name" }
    $alpha=[int]$alphaMatch.Groups[1].Value
    $lines.Add("static const unsigned char hud_mask_${name}[] = {")
    for ($ty=0; $ty -lt $height/8; ++$ty) {
        for ($tx=0; $tx -lt $width/8; ++$tx) {
            for ($row=0; $row -lt 4; ++$row) {
                $keep=0; $planes=@(0,0,0,0)
                for ($x=0; $x -lt 8; ++$x) {
                    $sx=4*$tx+[int][Math]::Floor($x/2); $sy=4*$ty+$row
                    $packed=$pixels[$sy*$stride+[int][Math]::Floor($sx/2)]
                    $color=if ($sx -band 1) { $packed -band 15 } else { $packed -shr 4 }
                    $bit=128 -shr $x
                    if ($color -eq $alpha) { $keep=$keep -bor $bit }
                    else { for ($p=0; $p -lt 4; ++$p) { if ($color -band (1 -shl $p)) { $planes[$p]=$planes[$p] -bor $bit } } }
                }
                $lines.Add('    '+((@($keep)+$planes | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', ')+',')
                $total+=5
            }
        }
    }
    $lines.Add('};')
}
if ($total -ne 1160) { throw "Unexpected mask size $total" }
$lines.Add('#endif')
[IO.File]::WriteAllLines($OutputHeader,$lines,[Text.Encoding]::ASCII)
Write-Output "Generated $total native HUD mask bytes from current sprite payloads."
